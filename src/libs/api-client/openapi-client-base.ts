import type { AxiosInstance } from 'axios';

type GeneratedApiConstructor = new (configuration: undefined, basePath: string, axios: AxiosInstance) => unknown;

export interface OpenApiClientOptions {
    axiosInstance: AxiosInstance;

    /**
     * Base URL of the API (e.g. an absolute URL during SSR, `''` in browsers); read when a client is first used.
     */
    getBasePath: () => string;
}

// Constants/Variables
const clientInstances = new WeakMap<typeof OpenApiClientBase, OpenApiClientBase>();
let clientOptions: OpenApiClientOptions | undefined;

// Classes

/**
 * Base of the API classes generated by `generateOpenApiClient` (`BaseAPI` extends it), giving each class a shared
 * instance through `use()`, e.g. `ProfileApi.use().getProfile()`.
 */
export class OpenApiClientBase {
    static use<T extends typeof OpenApiClientBase>(this: T) {
        let instance = clientInstances.get(this);
        if (!instance) {
            if (!clientOptions) throw new Error('configureOpenApiClient() must be called before using an API class');
            const GeneratedApi = this as unknown as GeneratedApiConstructor;
            instance = new GeneratedApi(
                undefined,
                clientOptions.getBasePath(),
                clientOptions.axiosInstance,
            ) as OpenApiClientBase;

            clientInstances.set(this, instance);
        }

        return instance as InstanceType<T>;
    }
}

// Functions

/**
 * Sets the axios instance and base URL of the generated API classes; call once before any `use()`.
 */
export function configureOpenApiClient(options: OpenApiClientOptions) {
    clientOptions = options;
}
