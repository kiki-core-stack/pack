import { execFileSync } from 'node:child_process';
import {
    mkdir,
    mkdtemp,
    rm,
    writeFile,
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import {
    dirname,
    join,
    relative,
} from 'node:path';
import { fileURLToPath } from 'node:url';

import {
    objectEntries,
    objectKeys,
    objectValues,
} from 'ts-extras';
import type { UserConfig } from 'tsdown';

type CustomExports = Extract<NonNullable<ExportsOptions['customExports']>, (...args: any[]) => any>;
type ExportsOptions = Extract<NonNullable<UserConfig['exports']>, { customExports?: unknown }>;
type ExportTarget = null | string | TypesOnlyExportTarget;

interface TypesOnlyExportTarget {
    default: null;
    types: string;
}

// Constants/Variables
const notExportedErrorCode = 'ERR_PACKAGE_PATH_NOT_EXPORTED';
const probePackageName = 'package-exports-probe';
const typesOnlyPathPattern = /(?:^|\/)types(?:\/|$)/;

// Functions

/**
 * Rewrites the exports generated by tsdown so that nested subpaths are exposed through
 * first-level wildcard patterns instead of explicit keys.
 *
 * TypeScript hides path completions for explicit export keys containing `/` (microsoft/TypeScript#57313),
 * while wildcard patterns complete one path segment at a time. Wildcards are only added for first-level
 * directories that contain nested entries, every reachable non-entry module inside them is blocked with
 * `null`, and modules under `types` paths are exported as types only. TypeScript ignores `null` targets in
 * completions and auto-imports, so blocked paths may still be suggested; they only fail to resolve.
 *
 * The result is verified with the Node.js resolver; the build fails if the resolvable subpaths differ
 * from the entries generated by tsdown.
 */
export const generatePackageExports: CustomExports = async (exports, { chunks }) => {
    const modules = new Set<string>();
    for (const chunk of objectValues(chunks).flat()) {
        if (chunk.type !== 'chunk') continue;
        const fileName = chunk.fileName.replaceAll('\\', '/');
        const moduleName = fileName.replace(/\.(?:d\.ts|js)$/, '');
        if (moduleName === fileName) continue;
        modules.add(moduleName);
        if (fileName.endsWith('.js') && isTypesOnly(moduleName) && chunk.exports.length) {
            throw new Error(`Types-only module "${fileName}" must not have runtime exports: ${chunk.exports.join(', ')}`);
        }
    }

    // Subpath ('' for the root entry) -> module name
    const entries = new Map<string, string>();
    for (const [key, value] of objectEntries(exports)) {
        if (key === './package.json') continue;
        const moduleName = typeof value === 'string' ? value.match(/^\.\/dist\/(.+)\.js$/)?.[1] : undefined;
        if (!moduleName) throw new Error(`Unsupported generated export "${key}": ${JSON.stringify(value)}`);
        entries.set(key === '.' ? '' : key.slice(2), moduleName);
    }

    const wildcardDirectories = new Set<string>();
    for (const subpath of entries.keys()) {
        const directory = getTopLevelDirectory(subpath);
        if (directory) wildcardDirectories.add(directory);
    }

    const generatedExports: Record<string, ExportTarget> = {};
    for (const directory of wildcardDirectories) generatedExports[`./${directory}/*`] = createExportTarget(`${directory}/*`);
    for (const [subpath, moduleName] of entries) {
        const directory = getTopLevelDirectory(subpath);
        const coveredByWildcard = directory !== undefined
          && wildcardDirectories.has(directory)
          && subpath === moduleName
          && isTypesOnly(subpath) === isTypesOnly(`${directory}/*`);

        if (!coveredByWildcard) generatedExports[subpath ? `./${subpath}` : '.'] = createExportTarget(moduleName);
    }

    // Block every module reachable through a wildcard that is not an entry with the same subpath
    const entrySubpaths = [...entries.keys()];
    for (const moduleName of modules) {
        const directory = getTopLevelDirectory(moduleName);
        if (directory === undefined || !wildcardDirectories.has(directory) || entries.has(moduleName)) continue;
        const segments = moduleName.split('/');
        // Prefer blocking the shallowest directory that contains no entries
        let blockedKey = `./${moduleName}`;
        for (let index = 2; index < segments.length; index++) {
            const blockedDirectory = segments.slice(0, index).join('/');
            if (!entrySubpaths.some((subpath) => subpath.startsWith(`${blockedDirectory}/`))) {
                blockedKey = `./${blockedDirectory}/*`;
                break;
            }
        }

        generatedExports[blockedKey] = null;
    }

    // Node.js ignores key order, but TypeScript generates auto-import specifiers from the first matching key,
    // so explicit entries must precede the wildcards (e.g. `./logger/node` before `./logger/*`)
    const getKeyGroup = (key: string) => {
        if (generatedExports[key] === null) return 2;
        return key.includes('*') ? 1 : 0;
    };

    const sortedExports: Record<string, ExportTarget> = {};
    objectKeys(generatedExports)
        .sort((a, b) => getKeyGroup(a) - getKeyGroup(b) || a.localeCompare(b))
        .forEach((key) => sortedExports[key] = generatedExports[key]!);

    if ('./package.json' in exports) sortedExports['./package.json'] = './package.json';
    await verifyExports(sortedExports, entries, modules);
    return sortedExports;
};

function createExportTarget(moduleName: string): ExportTarget {
    if (!isTypesOnly(moduleName)) return `./dist/${moduleName}.js`;
    return {
        /* eslint-disable perfectionist/sort-objects */
        types: `./dist/${moduleName}.d.ts`,
        default: null,
        /* eslint-enable perfectionist/sort-objects */
    };
}

function getTopLevelDirectory(path: string) {
    const separatorIndex = path.indexOf('/');
    return separatorIndex === -1 ? undefined : path.slice(0, separatorIndex);
}

function isTypesOnly(moduleName: string) {
    return typesOnlyPathPattern.test(moduleName);
}

async function verifyExports(
    exports: Record<string, ExportTarget>,
    entries: Map<string, string>,
    modules: Set<string>,
) {
    const subpaths = [
        ...new Set([
            ...entries.keys(),
            ...modules,
        ]),
    ];

    const directory = await mkdtemp(join(tmpdir(), `${probePackageName}-`));
    try {
        const packageDirectory = join(directory, 'node_modules', probePackageName);
        const files = [...modules].flatMap((moduleName) => [
            `dist/${moduleName}.js`,
            `dist/${moduleName}.d.ts`,
        ]);

        await Promise.all(files.map(async (file) => {
            await mkdir(dirname(join(packageDirectory, file)), { recursive: true });
            await writeFile(join(packageDirectory, file), '');
        }));

        await writeFile(
            join(packageDirectory, 'package.json'),
            JSON.stringify({
                exports,
                name: probePackageName,
                type: 'module',
            }),
        );

        const probePath = join(directory, 'probe.mjs');
        await writeFile(
            probePath,
            `
                import { readFileSync } from 'node:fs';

                const results = {};
                for (const specifier of JSON.parse(readFileSync(0, 'utf8'))) {
                    try {
                        results[specifier] = import.meta.resolve(specifier);
                    } catch (error) {
                        results[specifier] = error.code;
                    }
                }

                process.stdout.write(JSON.stringify(results));
            `,
        );

        const specifiers = subpaths.map((subpath) => subpath ? `${probePackageName}/${subpath}` : probePackageName);
        const resolve = (conditions: string[]) => {
            const output = execFileSync(
                process.execPath,
                [
                    ...conditions.map((condition) => `--conditions=${condition}`),
                    probePath,
                ],
                { input: JSON.stringify(specifiers) },
            );

            const results: Record<string, string> = JSON.parse(output.toString());
            return specifiers.map((specifier) => {
                const result = results[specifier]!;
                return result.startsWith('file:') ? relative(packageDirectory, fileURLToPath(result)).replaceAll('\\', '/') : result;
            });
        };

        const errors: string[] = [];
        const runtimeResults = resolve([]);
        const typesResults = resolve(['types']);
        subpaths.forEach((subpath, index) => {
            const moduleName = entries.get(subpath);
            const typesOnly = moduleName !== undefined && isTypesOnly(moduleName);
            const expectedRuntime = moduleName === undefined || typesOnly ? notExportedErrorCode : `dist/${moduleName}.js`;
            const expectedTypes = typesOnly ? `dist/${moduleName}.d.ts` : expectedRuntime;
            const displayName = subpath ? `./${subpath}` : '.';
            if (runtimeResults[index] !== expectedRuntime) {
                errors.push(`${displayName} (runtime): expected ${expectedRuntime}, got ${runtimeResults[index]}`);
            }

            if (typesResults[index] !== expectedTypes) {
                errors.push(`${displayName} (types): expected ${expectedTypes}, got ${typesResults[index]}`);
            }
        });

        if (errors.length) throw new Error(`Generated package exports do not match the entries:\n${errors.join('\n')}`);
    } finally {
        await rm(
            directory,
            {
                force: true,
                recursive: true,
            },
        );
    }
}
